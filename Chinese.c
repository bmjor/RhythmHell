const uint32_t ChineseWidth[] = {
    0, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 4, 2, 3, 3
};



uint32_t ChineseX,ChineseY; // cursor
//********Chinese_SetCursor*****************
// Move the cursor to the desired X- and Y-position.  The
// next character will be printed here.  X=0 is the leftmost
// column.  Y=0 is the top row.
// inputs: newX  new X-position of the cursor (0<=newX<=127)
//         newY  new Y-position of the cursor (0<=newY<=159)
// outputs: none
void Chinese_SetCursor(uint32_t newX, uint32_t newY){
  if((newX > 127) || (newY > 159)){    // bad input
    return;                            // do nothing
  }
  ChineseX = newX;
  ChineseY = newY;
}
// *************** Chinese_OutChar ********************
// Output one character to the LCD
// Position determined by Chinese_SetCursor command
// Inputs: 8-bit Chinese character
// Outputs: none
void Chinese_OutChar(Chinese_t ch){
    uint32_t w = ChineseWidth[ch];
  if((ChineseX+w)>127){ // won't fit
    ChineseX = 0;
    ChineseY += 8;
    if(ChineseY>159){
      ChineseY = 15;
    }
  }
  ST7735_DrawBitmap(ChineseX,ChineseY,ChineseFont[ch],w,8);
  ChineseX += w;
}
//********Chinese_OutString*****************
// Print a string of Chinese characters to the ST7735 LCD.
// Position determined by Chinese_SetCursor command
// The string will automatically wrap.
// inputs: ptr  pointer to end-terminated Chinese string
// outputs: none
void Chinese_OutString(Chinese_t *ptr){
  while(*ptr != null){
    Chinese_OutChar(*ptr);
    ptr = ptr + 1;
  }
}

